// Track used indices to avoid duplicates
var usedIndices = make(map[int]bool)

// GetRandomProbability returns a unique random probability set
func GetRandomProbability() (float64, float64, float64) {
    // Reset if all used
    if len(usedIndices) >= len(ProbabilityPool) {
        usedIndices = make(map[int]bool)
    }
    
    // Find unused index
    for {
        idx := rand.Intn(len(ProbabilityPool))
        if !usedIndices[idx] {
            usedIndices[idx] = true
            p := ProbabilityPool[idx]
            return p.Home, p.Draw, p.Away
        }
    }
}

// ResetUsedProbabilities resets the tracker (call daily)
func ResetUsedProbabilities() {
    usedIndices = make(map[int]bool)
}